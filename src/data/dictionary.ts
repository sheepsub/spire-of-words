/**
 * 动态干扰项生成器：
 * 根据正确词义与词性，在庞大词库中智能挑选 3 个相同词性（如动词对动词、名词对名词）的高逼真干扰项。
 * 彻底杜绝固定选项，每一次出牌都是全新挑战！
 */
export function getRandomDistractors(
  correctWord: string,
  correctMeaning: string,
  pos: string,
  count = 3
): string[] {
  // 筛选词性相近的词汇
  const cleanPos = pos ? pos.trim().toLowerCase() : '';
  const samePosEntries = DICTIONARY_WORDS.filter((entry) => {
    if (entry.word.toLowerCase() === correctWord.toLowerCase()) return false;
    if (entry.meaning === correctMeaning) return false;
    if (!cleanPos) return true;
    return entry.pos.toLowerCase().includes(cleanPos.slice(0, 1));
  });

  // 如果同词性足够多，则在同词性中乱序抽取
  const candidatePool = samePosEntries.length >= count ? samePosEntries : DICTIONARY_WORDS.filter(
    (e) => e.word.toLowerCase() !== correctWord.toLowerCase() && e.meaning !== correctMeaning
  );

  const shuffled = [...candidatePool].sort(() => Math.random() - 0.5);
  const picked: string[] = [];

  for (const item of shuffled) {
    if (!picked.includes(item.meaning) && item.meaning !== correctMeaning) {
      picked.push(item.meaning);
    }
    if (picked.length >= count) break;
  }

  // 保底补齐
  const fallbacks = ['沉沦堕落', '隐秘潜伏', '神圣加冕', '顽强抵抗', '万念俱灰'];
  for (const fb of fallbacks) {
    if (picked.length >= count) break;
    if (!picked.includes(fb) && fb !== correctMeaning) {
      picked.push(fb);
    }
  }

  return picked.slice(0, count);
}

/**
 * 依据单词或 ID 查询词典详细信息
 */
export function findDictionaryWord(wordOrId: string): DictionaryEntry | undefined {
  const query = wordOrId.trim().toLowerCase();
  return DICTIONARY_WORDS.find(
    (w) => w.word.toLowerCase() === query || w.id.toLowerCase() === query
  );
}
